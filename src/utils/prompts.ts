/**
 * 抢地主阶段Prompt生成函数
 * @param num 玩家人数：3 | 4
 * @param prePersons 前面玩家抢地主信息，按行动顺序
 * @param myHand 当前AI手牌数组
 * @returns prompt字符串，模型只输出JSON决策
 */
export const qiangDoudizuRules = (
  num: 3 | 4,
  prePersons: Array<{ id: string; action: "snatch" | "pass"; snatchScore?: number }>,
  myHand: string[]
) => `当前进入斗地主【抢地主】阶段，总玩家${num}人。
===基础规则===
1. 抢地主顺序：按玩家依次行动，轮到你决策。前面玩家行动记录：${JSON.stringify(prePersons)}
2. 可选动作：
    snatch：抢地主，可附带抢分snatchScore（一般1/2/3分，代表加倍）
    pass：不抢，放弃本轮抢地主资格
3. 判定逻辑：
    - 只要有玩家选择snatch，则最后一个抢地主的玩家成为地主；
    - 全部玩家都pass，本局流局，重新发牌。
4. 手牌信息：你的手牌myHand = ${JSON.stringify(myHand)}
${
  num === 3
    ? "3人局，手牌17张，底牌3张；有王炸、2，牌力强适合抢地主"
    : "4人局，手牌12张，底牌4张；无王炸，四张2是最强炸弹"
}

===抢地主AI决策策略===
1. 评估手牌牌力：
    - 高牌多（大王小王、多张2、炸弹），牌力强 → 倾向【抢地主】，可选择高抢分
    - 散牌多、缺少大牌、无炸弹 → 倾向【不抢(pass)】
2. 参考前置玩家动作：前面有人抢，需要评估自己牌力是否优于对手再决定继续抢；前面所有人都pass，牌力中等也可以尝试抢。
3. 抢地主拿到底牌，会一次性多${num}张牌，牌型可以重构；风险是1打${num - 1}个农民。

===输出约定===
1. 仅输出原始JSON，禁止多余文字、markdown、换行。
2. 返回字段说明：
    action: "snatch" | "pass"
    snatchScore: number | null，action=snatch时填写抢分；pass时为null
    reason：简短一句话，说明判断理由
示例：
{"action":"snatch","snatchScore":2,"reason":"手牌含王炸，大牌充足，适合抢地主"}
{"action":"pass","snatchScore":null,"reason":"散牌太多，缺少大牌，不抢地主"}
`;

/**
 * 斗地主出牌规则Prompt生成函数
 * @param num 玩家人数
 * @param landlordId 地主ID
 * @param myId 当前AI玩家ID
 * @param farmerIds 农民ID列表
 * @param currentHand 玩家当前手牌数组，例：["大王","小王","♠2","♥A"]
 * @param lastPlay 上家本轮打出的牌，null代表本轮首出
 * @param playedCards 全局已经打出过的所有牌（用于记牌）
 * @returns 规则prompt字符串，用于给大模型，模型只输出JSON
 */
export const doudizuRules = (
  num: 3 | 4,
  landlordId: string,
  myId: string,
  farmerIds: string[],
  currentHand: string[],
  lastPlay: string[] | null,
  playedCards: string[]
) => `你正在参与一场斗地主游戏，${num}人参与。
===基础规则===
1. 牌库：${num == 3 ? 54 : 52}张，${
  num == 3 ? "大王+小王+" : ""
}4种花色：A、2、K、Q、J、10、9、8、7、6、5、4、3；
牌大小排序：${num == 3 ? "大王>小王>" : ""}2>A>K>Q>J>10>9>8>7>6>5>4>3
2. ${num}个玩家：地主:${landlordId}，农民:${farmerIds.join("，")}；你是${
  myId === landlordId ? "地主" : "农民"
}。
3. 发牌：每人${num == 3 ? 17 : 12}张，底牌${num}张。
4. 胜负规则：地主1人对战${
  num - 1
}个农民。地主率先出完手牌地主胜利；任意一名农民先出完手牌，则农民胜利。
春天：地主整局一次牌都没出，农民获胜；反春天：农民整局一次牌都没出，地主获胜。

===合法牌型（严格校验，打出的牌必须全部存在于你的手牌currentHand）===
1. 单张：1张
2. 对子：2张点数相同
3. 三张：3张点数相同
4. 三带一：3张相同点数 + 任意1张单牌；禁止三带一对
5. 顺子：≥5张连续单牌；**不可包含2、王**；例：34567 ✔，23456 ❌
6. 连对：≥3组连续对子；**不可包含2、王**；例：334455 ✔，223344 ❌
7. 飞机：≥2组连续三张；**不可包含2、王**。两种合法形式：
   - 不带牌：仅连续三组；
   - 带牌：每组三张搭配1张单独牌；**每组必须都带一张，不能有的带有的不带，禁止带对子**
8. 四带二：4张同点数炸弹 + 任意2张单牌 / 一对；四带二不算炸弹，不能压普通炸弹
9. 炸弹：4张同点数，可以压制所有普通牌型；仅更大炸弹/王炸可以压制炸弹。
10. 王炸：仅3人局存在，大王+小王，全局最大，压制所有牌（含普通炸弹）；4人局**没有王炸**，4人局最大炸弹为4张2。

===出牌规则===
输入信息：
你的手牌currentHand：${JSON.stringify(currentHand)}
上一家本轮出牌lastPlay：${lastPlay ? JSON.stringify(lastPlay) : "null（本轮由你首发）"}
全局已经打出的所有牌playedCards：${JSON.stringify(playedCards)}

1. 出牌顺序：地主率先出牌，之后轮流出牌；
2. 如果lastPlay不为null：出牌必须满足【同牌型、点数更大】，或者选择不出。
3. 炸弹/王炸不受牌型限制，随时打出。
4. 一轮判定：连续2个玩家选择不出，则本轮结束，本轮第一个出牌的玩家获得新一轮首发权。
5. 硬性约束：打出的所有牌必须全部在currentHand内，绝对不能编造不存在的手牌。

##关于炸弹的特别规则
手牌存在炸弹时，尽量不要拆分炸弹作为对子/顺子/三带一/四带二使用。
炸弹使用时机：当没有同牌型大牌压制上家时，可以打出炸弹抢夺出牌权；谨慎使用炸弹，保留炸弹用于决胜。
${num == 3 ? "3人局双王是最大炸弹" : "4人局4张2是最大炸弹，本局不存在王炸"}

##斗地主AI出牌策略参考
#地主策略
- 核心目标：尽快打完手牌，压制农民，打断农民配合。
- 保留关键大牌（2、王），残局用来抢轮次、收尾。
- 记牌：参考playedCards，推算剩余关键大牌分布。
- 对手手牌张数少时，主动加压，逼迫对方消耗大牌。

#农民策略
- 核心目标：和其他农民配合，阻止地主跑完。
- 合理堵地主，必要时牺牲手牌，帮助队友。
- 保留大牌（2、王），用于打断地主连续出牌。
- 基于playedCards，推算地主剩余关键牌，规划出牌。

===输出约定===
1. 只返回原始JSON字符串，**不要markdown、不要解释文字、不要多余换行**。
2. play字段：出牌的牌数组，元素格式和手牌一致；不出则为null。
3. reason：简短中文，一句话说明决策理由。
4. 如果你打算出牌，但牌型非法/手牌不存在这些牌，必须返回 {"play":null,"reason":"牌非法，选择不出"}
输出JSON模板：{"play":["♠3","♥3"],"reason":"对子压制上家对子"}
`;
